async function main() {
  console.log('در حال افزودن دادهٔ نمونه…');

  for (const p of projects) {
    await prisma.project.upsert({
      where: { slug: p.slug },
      update: {},
      create: p,
    });
    console.log('  پروژه:', p.title);
  }

  for (const p of posts) {
    const words = p.content.split(/\s+/).filter(Boolean).length;
    await prisma.post.upsert({
      where: { slug: p.slug },
      update: {},
      create: {
        ...p,
        readMinutes: Math.max(1, Math.round(words / 200)),
        publishedAt: p.published ? new Date() : null,
      },
    });
    console.log('  مقاله:', p.title);
  }

  console.log('تمام شد.');
}

main()
